//! Пиксельный шрифт 5×7 для ASCII 32–127.
//!
//! Атлас генерируется процедурно при старте движка:
//!   * 128×64 RGBA текстура;
//!   * первые 96×48 — глифы в сетке 16×6 ячеек по 6×8 пикселей;
//!   * белый блок 4×4 в правом нижнем углу — для solid-color квадов.
//!
//! Каждый глиф — 5 колонок по байту; младшие 7 бит колонки задают
//! пиксели сверху вниз (bit 0 = верхний пиксель).

pub const ATLAS_W: u32 = 128;
pub const ATLAS_H: u32 = 64;

pub const GLYPH_W: u32 = 5;
pub const GLYPH_H: u32 = 7;
pub const GLYPH_CELL_W: u32 = 6;
pub const GLYPH_CELL_H: u32 = 8;
pub const ATLAS_COLS: u32 = 16;
pub const ATLAS_ROWS: u32 = 6;

pub const WHITE_BLOCK_X: u32 = 120;
pub const WHITE_BLOCK_Y: u32 = 56;
pub const WHITE_BLOCK_SIZE: u32 = 4;

/// Атлас — RGBA8. Вызывается один раз при старте Renderer.
pub fn generate_atlas() -> Vec<u8> {
    let mut data = vec![0u8; (ATLAS_W * ATLAS_H * 4) as usize];

    for (i, glyph) in FONT_GLYPHS.iter().enumerate() {
        let col = (i as u32) % ATLAS_COLS;
        let row = (i as u32) / ATLAS_COLS;
        let x0 = col * GLYPH_CELL_W;
        let y0 = row * GLYPH_CELL_H;

        for gx in 0..GLYPH_W {
            let c = glyph[gx as usize];
            for gy in 0..GLYPH_H {
                if (c >> gy) & 1 != 0 {
                    let px = x0 + gx;
                    let py = y0 + gy;
                    let idx = ((py * ATLAS_W + px) * 4) as usize;
                    data[idx] = 255;
                    data[idx + 1] = 255;
                    data[idx + 2] = 255;
                    data[idx + 3] = 255;
                }
            }
        }
    }

    // Белый блок для solid-квадов.
    for y in WHITE_BLOCK_Y..WHITE_BLOCK_Y + WHITE_BLOCK_SIZE {
        for x in WHITE_BLOCK_X..WHITE_BLOCK_X + WHITE_BLOCK_SIZE {
            let idx = ((y * ATLAS_W + x) * 4) as usize;
            data[idx] = 255;
            data[idx + 1] = 255;
            data[idx + 2] = 255;
            data[idx + 3] = 255;
        }
    }

    data
}

/// UV для конкретного символа.
pub fn glyph_uv(c: char) -> [f32; 4] {
    let idx = (c as u32).saturating_sub(32).min(95);
    let col = idx % ATLAS_COLS;
    let row = idx / ATLAS_COLS;

    let x0 = col * GLYPH_CELL_W;
    let y0 = row * GLYPH_CELL_H;
    let x1 = x0 + GLYPH_W;
    let y1 = y0 + GLYPH_H;

    let inv_w = 1.0 / ATLAS_W as f32;
    let inv_h = 1.0 / ATLAS_H as f32;
    [
        x0 as f32 * inv_w,
        y0 as f32 * inv_h,
        x1 as f32 * inv_w,
        y1 as f32 * inv_h,
    ]
}

/// UV белого блока (для solid-квадов).
pub fn white_uv() -> [f32; 4] {
    let x0 = WHITE_BLOCK_X;
    let y0 = WHITE_BLOCK_Y;
    let x1 = x0 + WHITE_BLOCK_SIZE;
    let y1 = y0 + WHITE_BLOCK_SIZE;

    let inv_w = 1.0 / ATLAS_W as f32;
    let inv_h = 1.0 / ATLAS_H as f32;
    [
        x0 as f32 * inv_w,
        y0 as f32 * inv_h,
        x1 as f32 * inv_w,
        y1 as f32 * inv_h,
    ]
}

